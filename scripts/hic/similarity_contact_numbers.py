#!/usr/bin/env python3
"""Print every number of paper_prep/manuscript_revision/similarity_contact_evidence.md from files in the repository, as
markdown tables per section (writes paper_prep/manuscript_revision/similarity_contact_numbers.md).

Sources (all in the repository): paper_prep/_brainstorming/similarity_contact_sources/ (scripts/hic/sc_collect.sbatch:
the paper's and every rerun's global_test.tsv, error-rate tables, simulation log lines, MAPQ filter counts, CHM13 PHR
loci at 50 kb, read lengths, duplication-graph Jaccard, CHM13 matched-duplication pairs tables, CiFi rerun lines);
paper_prep/_brainstorming/sim_hic_null/ (calibration, artefact-subtracted statistics, placement rates, real-read
profiles, rebalanced MAPQ >= 2 statistics, misassignment of the clean HG002 Hi-C null);
paper_prep/_brainstorming/matched_sd_control/ (matched pairs and per-matrix summaries); scripts/hic/contact_controls_r3m3.inter.txt
(partial Mantel); data/human_HG002_porec_20000bp_seqlevel.tsv (per-pair Jaccard of the 2,830 HG002 PHR pairs).
usage: similarity_contact_numbers.py [REPO_ROOT]"""
import collections, csv, glob, math, os, re, statistics, sys
from scipy.stats import spearmanr
R = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", ".."))
S = f"{R}/paper_prep/_brainstorming/similarity_contact_sources"; N = f"{R}/paper_prep/_brainstorming/sim_hic_null"
M = f"{R}/paper_prep/_brainstorming/matched_sd_control"; OUT = f"{R}/paper_prep/manuscript_revision/similarity_contact_numbers.md"
out = []; P = lambda *x: out.append(" ".join(map(str, x)))
f3 = lambda v: f"{v:.3f}"
def pc(v, d=None):  # percent: 1 decimal, 2 below 2%, 3 below 0.1%
    d = d if d is not None else (3 if abs(v) < 0.001 else 2 if abs(v) < 0.02 else 1); return f"{100 * v:.{d}f}%"
def tsv(p): return list(csv.DictReader(open(p), delimiter="\t"))
def gt(p):  # global_test.tsv: Mantel rho, its p, B/W, Mann-Whitney p
    r = {x["test"]: x for x in tsv(p)}; w = float(r["within_vs_between"]["within_mean"]); b = float(r["within_vs_between"]["between_mean"])
    return dict(mantel=float(r["mantel"]["U_statistic"]), p=float(r["mantel"]["p_value"]), bw=b / w, mw=float(r["within_vs_between"]["p_value"]))
G = lambda name: gt(f"{S}/global_test/{name}.global_test.tsv")
def summ(p): return {r["measure"]: float(r["value"]) for r in tsv(p)}
def sd(p): return {r["set"]: r for r in tsv(p)}
def subtract(p):  # subtract_artefact.py log: expected, removed, floor
    l = [x for x in open(p) if x.startswith("done ")][0]
    e = float(re.search(r"expected artefact ([0-9.]+)", l).group(1)); rm = float(re.search(r"removed ([0-9.]+)", l).group(1))
    return e, rm
def table(h, rows): P("| " + " | ".join(h) + " |"); P("|" + "---|" * len(h)); [P("| " + " | ".join(map(str, r)) + " |") for r in rows]; P("")

P("# Numbers behind similarity_contact_evidence.md"); P("")
P(f"Generated by `scripts/hic/similarity_contact_numbers.py` from files in the repository. Do not edit by hand."); P("")

# Mantel of the paper and of the cleaned matrices
cr = lambda name, r: gt(f"{N}/corrected_res/{name}.{r}.global_test.tsv")
P("## Mantel: paper, error-corrected (clean and realistic simulations)"); P("")
rows = []
for lab, paper, clean, real in (("Hi-C HG002", "paper_hg002", "hg002_hic", "hg002_hic_wprof"), ("Hi-C HG002, MAPQ >= 1", "mapq_HG002_mapq1", "hg002_hic_mapq1", "hg002_hic_mapq1_wprof"),
                                ("Hi-C CHM13", "paper_chm13", "chm13_hic", "chm13_hic_wprof"), ("Hi-C CHM13, MAPQ >= 1", "mapq_CHM13_mapq1", "chm13_hic_mapq1", "chm13_hic_mapq1_wprof"),
                                ("Pore-C", "paper_hg002_porec", "hg002_porec", "hg002_porec_wprof"), ("CiFi", "paper_hg002_cifi", "hg002_cifi", None),
                                ("CiFi, multi-mapping reads kept", "rerun_cifi_mq0", "hg002_cifi_mq0", None)):
    row = [lab]
    for r in (50000, 20000):
        row += [f3(G(f"{paper}_{r}")["mantel"]), f3(cr(clean, r)["mantel"]), f3(cr(real, r)["mantel"]) if real else ""]
    ex = [subtract(f"{N}/corrected_res/{n}.50000.subtract.log") for n in (clean, real) if n]
    row += [f"{ex[-1][1]:,.0f} of {ex[-1][0]:,.0f} ({pc(ex[-1][1] / ex[-1][0], 1)}; not removable {ex[-1][0] - ex[-1][1]:,.0f})"]
    pmax = max([cr(clean, r)["p"] for r in (50000, 20000)] + ([cr(real, r)["p"] for r in (50000, 20000)] if real else []))
    rows.append(row + ["< 0.0001 (0 of 10,000 permutations)" if pmax == 0 else f"{pmax:g}"])
table(["assay", "paper 50 kb", "clean 50 kb", "realistic 50 kb", "paper 20 kb", "clean 20 kb", "realistic 20 kb", "removed at 50 kb (last simulation)", "largest corrected p"], rows)
P("Corrected B/W, HG002 Hi-C 50 kb: clean", f3(cr("hg002_hic", 50000)["bw"]), "realistic", f3(cr("hg002_hic_wprof", 50000)["bw"]), "paper", f3(G("paper_hg002_50000")["bw"]),
  "; within/between p (realistic)", f"{cr('hg002_hic_wprof', 50000)['mw']:.3g}"); P("")

# Hi-C with MAPQ filters
P("## Hi-C with MAPQ filters (section 3)"); P("")
for l in open(f"{S}/mapq_filter_counts.txt"):
    t = int(re.search(r"total (\d+)", l).group(1)); k = {int(a): int(b) for a, b in re.findall(r"MAPQ >= (\d) on both reads (\d+)", l)}
    P(f"- total pairs {t:,}: MAPQ >= 1 {pc(k[1] / t, 1)}, MAPQ >= 2 {pc(k[2] / t, 2)}")
P("")
rows = []
for gname in ("HG002", "CHM13"):
    for r in (50000, 20000):
        a, m1, m2 = G(f"paper_{gname.lower()}_{r}"), G(f"mapq_{gname}_mapq1_{r}"), G(f"mapq_{gname}_mapq2_{r}")
        rows.append([gname, r, f3(a["mantel"]), f3(m1["mantel"]), f"{f3(m2['mantel'])} (p {m2['p']:.3g})", f"{a['bw']:.3f} / {m1['bw']:.3f} / {m2['bw']:.3f}"])
table(["genome", "resolution", "Mantel all", "MAPQ >= 1", "MAPQ >= 2", "B/W all / >=1 / >=2"], rows)
L = tsv(f"{S}/chm13_phr_loci_50kb.tsv"); lost = [x for x in L if int(x["weighted_bins_mapq2"]) == 0]
wa = [x for x in L if int(x["weighted_bins_all"]) > 0]
P(f"CHM13 PHR loci (>= 5 kb, on the Hi-C chromosomes): {len(L)}; with a balanced bin with all reads: {len(wa)}; of these, without any balanced bin at MAPQ >= 2: {sum(int(x['weighted_bins_mapq2']) == 0 for x in wa)}")
for x in L:
    if x["locus"].startswith(("chr22:", "chr15:")) and int(x["locus"].split(":")[1].split("-")[0]) < 1000000:
        P(f"- {x['locus']}: raw cis contacts per million {float(x['raw_cis_per_million_all']):.1f} (all reads) -> {float(x['raw_cis_per_million_mapq2']):.1f} (MAPQ >= 2)")
P("")
def pairs(p):
    return {(r["locus_a"], r["locus_b"]): float(r["jaccard"]) for r in tsv(p) if r["set"] == "PHR"}
a, b = pairs(f"{S}/sd_chm13_hic_50000.pairs.tsv"), pairs(f"{S}/sd_chm13_hic_mapq2_50000.pairs.tsv")
lostp = [v for k, v in a.items() if k not in b]; kept = [v for k, v in a.items() if k in b]
thr = sorted(a.values())[int(0.9 * len(a))]; top = [k for k, v in a.items() if v >= thr]
P(f"CHM13 PHR pairs (different chromosomes): all reads {len(a)}, MAPQ >= 2 {len(b)}; loci {len({x for k in a for x in k})} -> {len({x for k in b for x in k})};"
  f" sharing nothing (Jaccard 0) {sum(v == 0 for v in a.values())}")
P(f"- lost pairs {len(lostp)}: median Jaccard {statistics.median(lostp):.4f}, mean {statistics.mean(lostp):.3f}; kept {len(kept)}: median {statistics.median(kept):.4f}, mean {statistics.mean(kept):.3f}")
P(f"- top 10% of Jaccard (>= {thr:.4f}): {len(top)} pairs, {sum(k not in b for k in top)} lost ({pc(sum(k not in b for k in top) / len(top), 0)}); overall {len(lostp)} of {len(a)} lost ({pc(len(lostp) / len(a), 0)})")
c2 = summ(f"{N}/calib/chm13_hic_mapq2_rl150.summary.tsv"); P(f"- CHM13 MAPQ >= 2 arm-level rho on raw densities: {f3(c2['rho_jaccard_observed'])} ({c2['observed_total']:,.0f} contacts between PHRs)"); P("")
rows = []
for gname in ("chm13", "hg002"):
    for v in ("default", "madmax0", "nofilter"):
        w = [l for l in open(f"{N}/rebalance/{gname}_mapq2_{v}.weights.log") if l.startswith("50000 bp rebalanced")][0]
        k = re.search(r"PHR windows with at least one weighted bin (\d+) of (\d+)", w).groups()
        rows.append([gname, v, f"{k[0]} of {k[1]}"] + [f"{f3(x['mantel'])} (p {x['p']:.3g})" for x in (gt(f"{N}/rebalance/{gname}_mapq2_{v}.{r}.global_test.tsv") for r in (50000, 20000))])
table(["genome", "balancing", "PHR windows with a balanced bin (50 kb)", "Mantel 50 kb", "Mantel 20 kb"], rows)

# Matched duplication control
P("## Matched duplication control (section 4)"); P("")
for gname in ("chm13", "hg002"):
    rr = tsv(f"{M}/{gname}_msd_cen_c0.5.pairs.tsv"); ph = {r["phr_pair"]: r for r in rr if r["set"] == "PHR"}; co = [r for r in rr if r["set"] != "PHR"]
    m = {r["phr_pair"] for r in co}; mi = [float(ph[k]["identity"]) for k in m]; ui = [float(v["identity"]) for k, v in ph.items() if k not in m]
    P(f"- {gname}: PHR pairs {len(ph):,}, matched {len(m):,} (identity {statistics.mean(mi):.3f}, log10 length {statistics.mean(math.log10(float(ph[k]['aln_len'])) for k in m):.2f}),"
      f" unmatched {len(ui):,} (identity {statistics.mean(ui):.3f}), controls {len(co):,} (identity {statistics.mean(float(r['identity']) for r in co):.3f}, log10 length {statistics.mean(math.log10(float(r['aln_len'])) for r in co):.2f})")
P("")
rows = []
for lab, f in (("Hi-C HG002", "hg002_hic_50000"), ("Hi-C HG002, MAPQ >= 1", "hg002_hic_mapq1_50000"), ("Hi-C HG002, MAPQ >= 2", "hg002_hic_mapq2_50000"), ("Hi-C HG002, MAPQ >= 2, 20 kb", "hg002_hic_mapq2_20000"),
               ("Hi-C CHM13", "chm13_hic_50000"), ("Hi-C CHM13, MAPQ >= 1", "chm13_hic_mapq1_50000"), ("Hi-C CHM13, MAPQ >= 2", "chm13_hic_mapq2_50000"), ("Hi-C CHM13, MAPQ >= 2, 20 kb", "chm13_hic_mapq2_20000"),
               ("Hi-C CHM13, MAPQ >= 2, rebalanced", "chm13_hic_mapq2_madmax0_50000"), ("Hi-C CHM13, MAPQ >= 2, rebalanced, 20 kb", "chm13_hic_mapq2_madmax0_20000"),
               ("Pore-C HG002", "hg002_porec_50000"), ("CiFi HG002", "hg002_cifi_50000"), ("CiFi HG002, multi-mapping reads kept", "hg002_cifi_mq0_50000")):
    x = sd(f"{M}/contacts/{f}.summary.tsv"); d = x["PHR_minus_control"]
    rows.append([lab, f"{float(x['PHR']['rho']):.3f} ({int(x['PHR']['pairs']):,} pairs)", f"{float(x['control']['rho']):.3f}", f"{float(d['rho']):.3f} ({float(d['ci_low']):.3f} to {float(d['ci_high']):.3f})",
                 f"{int(x['PHR']['pairs_jaccard_gt0']):,} of {int(x['PHR']['pairs']):,} / {int(x['control']['pairs_jaccard_gt0']):,} of {int(x['control']['pairs']):,}", f"{float(x['PHR']['rho_jaccard_gt0']):.3f} / {float(x['control']['rho_jaccard_gt0']):.3f}"])
table(["matrix", "PHR rho", "control rho", "PHR minus control (95% CI)", "pairs with Jaccard > 0, PHR / control", "rho on Jaccard > 0, PHR / control"], rows)
for l in open(f"{S}/sd_graph_jaccard.tsv"):
    if l.startswith("measure"): continue
    k, v = l.rstrip("\n").split("\t")
    P(f"- {k}: " + (f"{int(v):,}" if k.startswith("ordered") else f"{float(v):.3f}" if k in ("median", "p90", "p99", "max") else re.sub(r"jaccard ([0-9.]+)", lambda m: f"jaccard {float(m.group(1)):.3f}", v)))
P("")

# Confounders
P("## Partial Mantel (section 5)"); P("")
for l in open(f"{R}/scripts/hic/contact_controls_r3m3.inter.txt"):
    if "\tpartial\t" in l or "\tmantel\t" in l and "pairs" in l.split("\t")[2]: P("-", l.rstrip("\n").replace("\t", " | "))
P("")

# Simulations
P("## Simulations (section 6)"); P("")
P("Read lengths of the real Hi-C reads sampled along whole files:"); [P(f"- {r['sample']} mate {r['mate']}: {int(r['reads']):,} reads, mean {r['mean']}, min {r['min']}, max {r['max']}") for r in tsv(f"{S}/read_lengths.tsv")]; P("")
rows = []
def er(p, s, q="0"): return [r for r in tsv(p) if r.get("set", r.get("mate")) == s and r["min_mapq"] == q][0]
for lab, p, s in (("HG002 R1 real", f"{N}/realistic/hg002_hic_whole.real_rates.tsv", "1"), ("HG002 R1 realistic", f"{S}/errrate/errrate6_hg002_m1.rates.tsv", "sim"),
                  ("HG002 R1 clean", f"{S}/errrate/errrate2_hg002.rates.tsv", "sim"), ("HG002 R2 real", f"{N}/realistic/hg002_hic_whole.real_rates.tsv", "2"),
                  ("HG002 R2 realistic", f"{S}/errrate/errrate6_hg002_m2.rates.tsv", "sim"), ("CHM13 R1 real", f"{N}/realistic/chm13_hic_whole.real_rates.tsv", "1"),
                  ("CHM13 R1 realistic", f"{S}/errrate/errrate6_chm13_m1.rates.tsv", "sim"), ("CHM13 R1 clean", f"{S}/errrate/errrate2_chm13.rates.tsv", "sim"),
                  ("CHM13 R2 real", f"{N}/realistic/chm13_hic_whole.real_rates.tsv", "2"), ("CHM13 R2 realistic", f"{S}/errrate/errrate6_chm13_m2.rates.tsv", "sim")):
    x = er(p, s); rows.append([lab, pc(float(x["mismatch_per_base"]), 2), pc(float(x["softclip_per_base"])), pc(float(x["frac_0mm"]))])
table(["Hi-C reads (all MAPQ)", "mismatches per aligned base", "soft-clipped bases", "reads with 0 mismatches"], rows)
rows = []
for lab, p, s in (("Pore-C real", f"{N}/realistic/hg002_porec_whole.real_rates.tsv", "real"), ("Pore-C realistic", f"{S}/errrate/errrate6_porec.rates.tsv", "sim"),
                  ("Pore-C clean", f"{S}/errrate/errrate2_porec.rates.tsv", "sim"), ("CiFi real (first 2,000 reads)", f"{S}/errrate/errrate2_cifi.rates.tsv", "real"), ("CiFi clean", f"{S}/errrate/errrate2_cifi.rates.tsv", "sim")):
    x = er(p, s); rows.append([lab, pc(float(x["nm_per_base"]), 2 if float(x["nm_per_base"]) > 0.005 else 3), pc(float(x["divergence"]), 2 if float(x["divergence"]) > 0.005 else 3), pc(float(x["softclip_per_base"]))])
table(["monomers (all MAPQ)", "edit distance per aligned base", "divergence", "soft-clipped bases"], rows)
P("Mismatches by position in the CHM13 R1 files (first 100,000 reads vs reads 100,001-200,000):")
for f in ("rep1", "rep2"):
    v = [float(er(f"{S}/errrate/errrate5_chm13_{f}_skip{k}.rates.tsv", "real")["mismatch_per_base"]) for k in (0, 100000)]
    P(f"- {f}: {pc(v[0], 2)} vs {pc(v[1], 2)}")
P("")
rb = lambda p: {r["min_mapq"]: r for r in tsv(p)}
rows = []
for lab, cl, re_ in (("Hi-C HG002", f"{N}/hg002_null_pk40.rates_by_mapq.tsv", f"{N}/realistic/null_wprof_pk40.rates_by_mapq.tsv"), ("Hi-C CHM13", f"{N}/chm13_null_rl150.rates_by_mapq.tsv", f"{N}/realistic/chm13_null_wprof_pk40.rates_by_mapq.tsv")):
    c, r = rb(cl), rb(re_)
    rows.append([lab, pc(float(c["0"]["rate_another_arm"])), pc(float(r["0"]["rate_another_arm"])), pc(float(c["2"]["rate_another_arm"]), 3), pc(float(r["2"]["rate_another_arm"]), 2),
                 f"{pc(int(r['1']['pairs']) / int(r['0']['pairs']))} / {pc(int(r['2']['pairs']) / int(r['0']['pairs']))}"])
ev = collections.defaultdict(list)
for l in open(f"{S}/sim_log_lines.tsv"):
    k, t = l.rstrip("\n").split("\t", 1)
    if t.startswith("evaluate:") and "of another arm" in t: ev[k].append(float(re.search(r"of another arm \d+ \(([0-9.]+)\)", t).group(1)))  # order: --min-mapq 1, then 0
for lab, cl, re_ in (("Pore-C (unique = --min-mapq 1, then 0)", "simporec.2882915", "wsim_porec.2889814"), ("CiFi", "simcifi.2882916", None)):
    rows.append([lab, pc(ev[cl][1]), pc(ev[re_][1]) if re_ else "", pc(ev[cl][0], 2), pc(ev[re_][0], 2) if re_ else "", ""])
table(["simulation", "all reads, clean", "all reads, realistic", "unique, clean", "unique, realistic", "pairs passing MAPQ >= 1 / >= 2 (realistic Hi-C)"], rows)
mis = collections.defaultdict(float)  # mean of the two directional rates of an unordered pair of ends on different arms
for r in tsv(f"{N}/hg002_null_pk40.misassign.tsv"):
    if re.sub(r"_(MATERNAL|PATERNAL)", "", r["end_a"]) != re.sub(r"_(MATERNAL|PATERNAL)", "", r["end_b"]): mis[frozenset((r["end_a"], r["end_b"]))] += float(r["rate"]) / 2
bed = {(l.split("\t")[0], int(l.split("\t")[1])): l.rstrip("\n").split("\t")[3] for l in open(f"{M}/hg002_phr_regions.bed")}
def end(s):  # HG002#1#chr10:2204-72204_chr10_parm -> chr10_PATERNAL_p (haplotype 1 = PATERNAL, checked against the BED coordinates)
    h, rest = s.split("#")[1], s.split("#")[2]; ch, rng = rest.split("_")[0].split(":")
    k = (f"{ch}_{'PATERNAL' if h == '1' else 'MATERNAL'}", int(rng.split("-")[0]))
    if k not in bed: sys.exit(f"FATAL {s} has no PHR region in hg002_phr_regions.bed")
    return bed[k]
X = [(mis.get(frozenset((end(r["seq_a"]), end(r["seq_b"]))), 0.0), float(r["jaccard"])) for r in tsv(f"{R}/data/human_HG002_porec_20000bp_seqlevel.tsv")]
P(f"Clean HG002 Hi-C null: placement rate into the PHR of the other end (mean of the two directions) vs per-pair Jaccard over {len(X):,} pairs:"
  f" Spearman rho {spearmanr([x[0] for x in X], [x[1] for x in X])[0]:.3f}; pairs with a nonzero rate {sum(x[0] > 0 for x in X)}")
P("")

