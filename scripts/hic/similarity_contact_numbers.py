# CiFi rerun
P("## CiFi rerun (section 9)"); P("")
cp = open(f"{S}/rerun_cifi.compare.txt").read().strip(); v = [int(x) for x in re.findall(r"(\d+) vs (\d+)", cp)[0] + re.findall(r"total counts (\d+) vs (\d+)", cp)[0]] + [int(re.search(r"differing pixels (\d+)", cp).group(1))]
